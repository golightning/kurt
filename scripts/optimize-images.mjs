// Turns the originals in assets/source/ into responsive AVIF + WebP sets in public/img/,
// and writes src/data/images.ts so the <Picture> component never guesses which widths
// exist. The live site ships a 2.76 MB JPEG; this is the answer to that.
import sharp from 'sharp'
import { readdir, mkdir, stat, writeFile } from 'node:fs/promises'
import { join, parse } from 'node:path'

const SRC = 'assets/source'
const OUT = 'public/img'
const WIDTHS = [640, 1024, 1600, 2048]

await mkdir(OUT, { recursive: true })
const files = (await readdir(SRC)).filter((f) => /\.(jpe?g|png)$/i.test(f))

const manifest = {}
const report = []
let before = 0
let after = 0

for (const file of files) {
  const { name } = parse(file)
  const input = join(SRC, file)
  const meta = await sharp(input).metadata()
  const srcWidth = meta.width ?? 0
  const originalBytes = (await stat(input)).size
  before += originalBytes

  // Only upscale never; but always emit at least one variant, at the source's own
  // width, so a small original still gets a usable file instead of being skipped.
  const widths = WIDTHS.filter((w) => w <= srcWidth)
  if (widths.length === 0) widths.push(srcWidth)

  let largest = 0
  for (const w of widths) {
    const base = sharp(input).resize({ width: w, withoutEnlargement: true })
    await base.clone().avif({ quality: 52, effort: 6 }).toFile(join(OUT, `${name}-${w}.avif`))
    await base.clone().webp({ quality: 76 }).toFile(join(OUT, `${name}-${w}.webp`))
    largest = Math.max(largest, (await stat(join(OUT, `${name}-${w}.avif`))).size)
  }

  manifest[name] = widths
  after += largest
  report.push([file, originalBytes, largest])
}

const ts = `// GENERATED by scripts/optimize-images.mjs — do not edit by hand.
// Which rendered widths actually exist per image, so <Picture> cannot reference a file
// that was never produced (a small original yields fewer variants than a large one).

export const imageWidths: Record<string, number[]> = ${JSON.stringify(manifest, null, 2)}

export function widthsFor(base: string): number[] {
  const key = base.replace(/^\\/img\\//, '')
  return imageWidths[key] ?? [640]
}
`
await writeFile('src/data/images.ts', ts)

const kb = (n) => `${(n / 1024).toFixed(0)} KB`
report.sort((a, b) => b[1] - a[1])
for (const [file, o, n] of report.slice(0, 5)) {
  console.log(`  ${file.padEnd(42)} ${kb(o).padStart(9)} -> ${kb(n).padStart(8)} AVIF  (-${(100 - (n / o) * 100).toFixed(0)}%)`)
}
console.log(`\n${files.length} Bilder, grösste AVIF-Variante je Bild:`)
console.log(`  ${(before / 1024 / 1024).toFixed(2)} MB -> ${(after / 1024 / 1024).toFixed(2)} MB  (-${(100 - (after / before) * 100).toFixed(0)}%)`)
