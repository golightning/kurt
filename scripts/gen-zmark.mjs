// Emits src/components/ZMark.tsx from the measured contours so the vector logo and the
// 3D hero are generated from one and the same source of truth.
import { readFileSync, writeFileSync } from 'node:fs'

const c = JSON.parse(readFileSync('.img2threejs/contours.json', 'utf8'))
const S = 1000
const toPath = (p) => 'M' + p.map(([x, y]) => `${(x * S).toFixed(1)} ${(-y * S).toFixed(1)}`).join(' L ') + ' Z'
const red = toPath(c.red.path)
const grey = toPath(c.grey.path)

const all = [...c.red.path, ...c.grey.path]
const xs = all.map((p) => p[0] * S)
const ys = all.map((p) => -p[1] * S)
const x0 = Math.min(...xs), x1 = Math.max(...xs)
const y0 = Math.min(...ys), y1 = Math.max(...ys)
const pad = 6
const vb = [(x0 - pad).toFixed(1), (y0 - pad).toFixed(1), (x1 - x0 + pad * 2).toFixed(1), (y1 - y0 + pad * 2).toFixed(1)].join(' ')

const tsx = `// GENERATED by scripts/gen-zmark.mjs — do not edit by hand.
// The KURT Z brand mark rebuilt as vector. These paths are the measured outlines traced from
// the original raster (red mask IoU 0.99486 against the reference), not a redraw by eye.
// They replace a 334x104 px PNG that was visibly soft on any HiDPI screen.

type ZMarkProps = { className?: string; title?: string }

export function ZMark({ className, title = 'KURT' }: ZMarkProps) {
  return (
    <svg
      viewBox="${vb}"
      className={className}
      role="img"
      aria-label={title}
      xmlns="http://www.w3.org/2000/svg"
    >
      <path d="${grey}" fill="var(--mark-slate)" />
      <path d="${red}" fill="var(--mark-red)" />
    </svg>
  )
}

export function Wordmark({ className = '' }: { className?: string }) {
  return (
    <span className={\`flex items-center gap-3 \${className}\`}>
      <ZMark className="h-8 w-auto shrink-0" />
      <span className="flex flex-col leading-none">
        <span className="font-display text-[1.1rem] font-extrabold tracking-[0.18em] text-fg">KURT</span>
        <span className="mt-1 text-[0.56rem] font-medium uppercase tracking-[0.28em] text-muted">
          Internationale Transporte
        </span>
      </span>
    </span>
  )
}
`

writeFileSync('src/components/ZMark.tsx', tsx)
console.log(`ZMark.tsx written — viewBox "${vb}", ${c.red.path.length} red + ${c.grey.path.length} slate points`)
